-- YAP beta fixes: profile RLS, notification events, replies, and profile image uploads.
-- Run once in Supabase Dashboard > SQL Editor. Safe to rerun.

begin;

-- The browser may create a profile only for the currently authenticated account.
-- Profiles are visible to signed-in users so people can search a username and see
-- the author information shown on posts.
alter table public.profiles enable row level security;
grant select, insert, update on public.profiles to authenticated;

do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname='public' and tablename='profiles'
  loop
    execute format('drop policy if exists %I on public.profiles',p.policyname);
  end loop;
end $$;

create policy "profiles_signed_in_read"
  on public.profiles for select to authenticated using (true);
create policy "profiles_insert_self"
  on public.profiles for insert to authenticated with check ((select auth.uid()) = id);
create policy "profiles_update_self"
  on public.profiles for update to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

-- In-app notifications. Writes are generated by tightly scoped table triggers.
create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  recipient_id uuid not null references auth.users(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  kind text not null check (kind in ('friend_request','friend_accepted','like','comment','reply')),
  body text not null,
  post_id uuid references public.posts(id) on delete cascade,
  comment_id uuid references public.comments(id) on delete cascade,
  friend_request_id uuid references public.friend_requests(id) on delete cascade,
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists notifications_recipient_created_idx
  on public.notifications(recipient_id, created_at desc);
create index if not exists notifications_unread_idx
  on public.notifications(recipient_id) where read_at is null;

alter table public.notifications enable row level security;
grant select on public.notifications to authenticated;
revoke insert, update, delete on public.notifications from anon, authenticated;
grant update (read_at) on public.notifications to authenticated;

drop policy if exists "notifications_read_self" on public.notifications;
create policy "notifications_read_self"
  on public.notifications for select to authenticated
  using ((select auth.uid()) = recipient_id);
drop policy if exists "notifications_mark_read_self" on public.notifications;
create policy "notifications_mark_read_self"
  on public.notifications for update to authenticated
  using ((select auth.uid()) = recipient_id)
  with check ((select auth.uid()) = recipient_id);

-- Add parent references so a comment can be a reply and reply notifications
-- identify both the post author and the parent commenter.
alter table public.comments
  add column if not exists parent_comment_id uuid references public.comments(id) on delete cascade;
create index if not exists comments_parent_comment_id_idx
  on public.comments(parent_comment_id) where parent_comment_id is not null;
create unique index if not exists comments_id_post_id_unique
  on public.comments(id, post_id);
do $
begin
  if not exists (select 1 from pg_constraint where conname='comments_parent_same_post_fk' and conrelid='public.comments'::regclass) then
    alter table public.comments add constraint comments_parent_same_post_fk
      foreign key (parent_comment_id, post_id) references public.comments(id, post_id) on delete cascade;
  end if;
end $;

-- Comments follow the same audience as their YAP.
alter table public.comments enable row level security;
do $
declare p record;
begin
  for p in select policyname from pg_policies where schemaname='public' and tablename='comments'
  loop
    execute format('drop policy if exists %I on public.comments',p.policyname);
  end loop;
end $;
create policy "comments_read_visible_posts"
  on public.comments for select to authenticated
  using (exists (
    select 1 from public.posts p
    where p.id=comments.post_id
      and (p.author_id=(select auth.uid()) or public.are_yap_friends((select auth.uid()),p.author_id))
  ));
create policy "comments_insert_visible_posts"
  on public.comments for insert to authenticated
  with check (author_id=(select auth.uid()) and exists (
    select 1 from public.posts p
    where p.id=comments.post_id
      and (p.author_id=(select auth.uid()) or public.are_yap_friends((select auth.uid()),p.author_id))
  ));
create policy "comments_update_own"
  on public.comments for update to authenticated
  using (author_id=(select auth.uid())) with check (author_id=(select auth.uid()));
create policy "comments_delete_own"
  on public.comments for delete to authenticated using (author_id=(select auth.uid()));

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create or replace function private.notify_friend_request()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare actor_name text;
begin
  if (select auth.uid()) is distinct from new.requester_id then return new; end if;
  select p.display_name into actor_name from public.profiles p where p.id = new.requester_id;
  insert into public.notifications(recipient_id, actor_id, kind, body, friend_request_id)
  values (new.recipient_id, new.requester_id, 'friend_request',
          coalesce(actor_name,'Someone') || ' sent you a friend request.', new.id);
  return new;
end;
$$;
revoke all on function private.notify_friend_request() from public, anon, authenticated;
drop trigger if exists notify_friend_request_created on public.friend_requests;
create trigger notify_friend_request_created
  after insert on public.friend_requests
  for each row execute function private.notify_friend_request();

create or replace function private.notify_friend_request_accepted()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare actor_name text;
begin
  if old.status <> 'pending' or new.status <> 'accepted'
     or (select auth.uid()) is distinct from new.recipient_id then return new; end if;
  select p.display_name into actor_name from public.profiles p where p.id = new.recipient_id;
  insert into public.notifications(recipient_id, actor_id, kind, body, friend_request_id)
  values (new.requester_id, new.recipient_id, 'friend_accepted',
          coalesce(actor_name,'Someone') || ' accepted your friend request.', new.id);
  return new;
end;
$$;
revoke all on function private.notify_friend_request_accepted() from public, anon, authenticated;
drop trigger if exists notify_friend_request_accepted on public.friend_requests;
create trigger notify_friend_request_accepted
  after update of status on public.friend_requests
  for each row execute function private.notify_friend_request_accepted();

create or replace function private.notify_yap_like()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare post_owner uuid; actor_name text;
begin
  if (select auth.uid()) is distinct from new.user_id then return new; end if;
  select p.author_id into post_owner from public.posts p where p.id = new.post_id;
  if post_owner is null or post_owner = new.user_id then return new; end if;
  select p.display_name into actor_name from public.profiles p where p.id = new.user_id;
  insert into public.notifications(recipient_id, actor_id, kind, body, post_id)
  values (post_owner, new.user_id, 'like',
          coalesce(actor_name,'Someone') || ' liked your YAP.', new.post_id);
  return new;
end;
$$;
revoke all on function private.notify_yap_like() from public, anon, authenticated;
drop trigger if exists notify_yap_like_created on public.likes;
create trigger notify_yap_like_created after insert on public.likes
  for each row execute function private.notify_yap_like();

create or replace function private.notify_yap_comment()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare post_owner uuid; parent_owner uuid; actor_name text; excerpt text;
begin
  if (select auth.uid()) is distinct from new.author_id then return new; end if;
  select p.author_id into post_owner from public.posts p where p.id = new.post_id;
  select p.display_name into actor_name from public.profiles p where p.id = new.author_id;
  excerpt := left(regexp_replace(coalesce(new.text,''), '[[:space:]]+', ' ', 'g'), 100);

  if new.parent_comment_id is not null then
    select c.author_id into parent_owner from public.comments c where c.id = new.parent_comment_id;
    if parent_owner is not null and parent_owner <> new.author_id then
      insert into public.notifications(recipient_id, actor_id, kind, body, post_id, comment_id)
      values (parent_owner, new.author_id, 'reply',
              coalesce(actor_name,'Someone') || ' replied to your comment: ' || excerpt,
              new.post_id, new.id);
    end if;
  end if;

  if post_owner is not null and post_owner <> new.author_id
     and (new.parent_comment_id is null or post_owner is distinct from parent_owner) then
    insert into public.notifications(recipient_id, actor_id, kind, body, post_id, comment_id)
    values (post_owner, new.author_id, 'comment',
            coalesce(actor_name,'Someone') || ' commented on your YAP: ' || excerpt,
            new.post_id, new.id);
  end if;
  return new;
end;
$$;
revoke all on function private.notify_yap_comment() from public, anon, authenticated;
drop trigger if exists notify_yap_comment_created on public.comments;
create trigger notify_yap_comment_created after insert on public.comments
  for each row execute function private.notify_yap_comment();

-- A public bucket is needed because avatar URLs are displayed to other users.
-- Per-user storage policies limit who can upload or replace objects in each folder.
insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('yap-media','yap-media',true,5242880,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public=true, file_size_limit=5242880,
  allowed_mime_types=array['image/jpeg','image/png','image/webp','image/gif'];

drop policy if exists "yap_media_owner_select" on storage.objects;
create policy "yap_media_owner_select" on storage.objects for select to authenticated
  using (bucket_id='yap-media' and (storage.foldername(name))[1]=(select auth.uid())::text);
drop policy if exists "yap_media_owner_insert" on storage.objects;
create policy "yap_media_owner_insert" on storage.objects for insert to authenticated
  with check (bucket_id='yap-media' and (storage.foldername(name))[1]=(select auth.uid())::text);
drop policy if exists "yap_media_owner_update" on storage.objects;
create policy "yap_media_owner_update" on storage.objects for update to authenticated
  using (bucket_id='yap-media' and (storage.foldername(name))[1]=(select auth.uid())::text)
  with check (bucket_id='yap-media' and (storage.foldername(name))[1]=(select auth.uid())::text);
drop policy if exists "yap_media_owner_delete" on storage.objects;
create policy "yap_media_owner_delete" on storage.objects for delete to authenticated
  using (bucket_id='yap-media' and (storage.foldername(name))[1]=(select auth.uid())::text);

-- Realtime updates the bell badge while the app is open.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end $$;

commit;
